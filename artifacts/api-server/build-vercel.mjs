import { createRequire } from "node:module";
import { mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build as esbuild } from "esbuild";

globalThis.require = createRequire(import.meta.url);

const artifactDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(artifactDir, "..", "..");
const functionsDir = path.resolve(repoRoot, "api");
const outfile = path.resolve(functionsDir, "[...route].mjs");

mkdirSync(functionsDir, { recursive: true });

// Bundles the Express app into a single self-contained Vercel serverless
// function at <repo>/api/[...route].mjs. Because every dependency is inlined,
// the function needs no node_modules at runtime.
